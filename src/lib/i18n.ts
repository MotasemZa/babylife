/** Root path for a language ('' for English, '/ar' for Arabic). */
export function base(lang: Lang): string {
  return lang === 'ar' ? '/ar' : '';
}

/** The same path in the other language, for the header switcher. */
export function altPath(lang: Lang, path: string): string {
  if (lang === 'ar') return path.replace(/^\/ar/, '') || '/';
  return '/ar' + (path === '/' ? '/' : path);
}

export function fmtDate(lang: Lang, iso: string): string {
  return new Date(iso + 'T12:00:00Z').toLocaleDateString(lang === 'ar' ? 'ar-JO' : 'en-GB', {
    year: 'numeric', month: 'long', day: 'numeric',
  });
}

export function readMinutes(html: string): number {
  const words = html.replace(/<[^>]+>/g, ' ').split(/\s+/).filter(Boolean).length;
  return Math.max(1, Math.ceil(words / 200));
}
